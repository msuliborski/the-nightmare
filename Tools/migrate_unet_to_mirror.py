#!/usr/bin/env python3
"""One-off migration of serialized UNET components (Unity 2018) to Mirror, done on the YAML of prefabs
and scenes because the Unity 6 editor can no longer load the UNET scripts to upgrade them itself.

- NetworkIdentity       -> Mirror NetworkIdentity (serverOnly kept; ids are regenerated by Mirror)
- NetworkTransform      -> Mirror NetworkTransformReliable (client authority -> SyncDirection.ClientToServer)
- NetworkTransformChild -> Mirror NetworkTransformReliable on the same object with `target` = the child
- NetworkAnimator       -> Mirror NetworkAnimator
- NetworkStartPosition  -> Mirror NetworkStartPosition
- NetworkManagerHUD     -> removed (the game has its own lobby UI)
- NetworkManager fields -> Mirror names, plus a KcpTransport component
- NetworkIdentity on child objects or on prefabs that are never spawned (weapons, arrow) -> removed:
  Mirror allows one identity per networked object, at its root.
Prefab-instance overrides in other files that target these components are renamed or dropped.

Usage: python3 Tools/migrate_unet_to_mirror.py   (from the repository root; idempotent)
"""
import glob
import os
import random
import re

UNET = 'dc443db3e92b4983b9738c1131f555cb'
ID, NT, NTC, NA, NSP, HUD, NM = '372142912', '-1768714887', '-1267208747', '1590678366', '-1050975500', '227461547', '-822479833'
MIRROR = {
    'identity': '9b91ecbcc199f4492b9a91e820070131',
    'transform': '8ff3ba0becae47b8b9381191598957c8',  # NetworkTransformReliable
    'animator': '7f6f3bf89aa97405989c802ba270f815',
    'startpos': '41f84591ce72545258ea98cb7518d8b9',
    'kcp': '6b0fecffa3f624585964b0d0eb21b18e',
}
CUSTOM_NM = '10e66068d9290094b9fbe6d56b4c4154'
MIRROR_NM = '8aab4c8111b7c411b9b92cf3dbc5bd4e'
NEVER_SPAWNED = ['Assets/Prefabs/Player/Arrow.prefab', 'Assets/Prefabs/Weapons/Pistol/Pistol.prefab',
                 'Assets/Prefabs/Weapons/Rifle/Rifle.prefab']
NM_FIELDS = {'m_DontDestroyOnLoad': 'dontDestroyOnLoad', 'm_RunInBackground': 'runInBackground',
             'm_NetworkAddress': 'networkAddress', 'm_MaxConnections': 'maxConnections',
             'm_OfflineScene': 'offlineScene', 'm_OnlineScene': 'onlineScene', 'm_PlayerPrefab': 'playerPrefab',
             'm_AutoCreatePlayer': 'autoCreatePlayer', 'm_PlayerSpawnMethod': 'playerSpawnMethod',
             'm_SpawnPrefabs': 'spawnPrefabs'}
STD = ('m_ObjectHideFlags', 'm_CorrespondingSourceObject', 'm_PrefabInstance', 'm_PrefabAsset', 'm_GameObject',
       'm_Enabled', 'm_EditorHideFlags', 'm_Script', 'm_Name', 'm_EditorClassIdentifier')

HEADER = re.compile(r'^--- !u!(\d+) &(-?\d+)( stripped)?.*$', re.M)


def parse(text):
    parts = []
    matches = list(HEADER.finditer(text))
    preamble = text[:matches[0].start()] if matches else text
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        parts.append({'cls': m.group(1), 'id': m.group(2), 'header': m.group(0) + '\n',
                      'body': text[m.end() + 1:end]})
    return preamble, parts


def script(body):
    m = re.search(r'm_Script: \{fileID: (-?\d+), guid: (\w+)', body)
    return (m.group(1), m.group(2)) if m else (None, None)


def field(body, name):
    m = re.search(r'^  %s: (.*)$' % re.escape(name), body, re.M)
    return m.group(1) if m else None


def std_lines(body, new_script):
    # Keep the class line ("MonoBehaviour:") and the standard Unity fields; drop the UNET fields.
    out = [body.splitlines(True)[0]]
    for line in body.splitlines(True)[1:]:
        key = line.strip().split(':')[0]
        if line.startswith('  ') and not line.startswith('   ') and key in STD:
            out.append(new_script if key == 'm_Script' else line)
    return ''.join(out)


def guid_of(path):
    return re.search(r'guid: (\w+)', open(path + '.meta').read()).group(1)


def main():
    files = glob.glob('Assets/**/*.prefab', recursive=True) + glob.glob('Assets/**/*.unity', recursive=True)
    # skip Mirror itself and binary-serialized assets (text YAML starts with %YAML)
    files = [f for f in files if '/Mirror/' not in f and open(f, 'rb').read(5) == b'%YAML']

    # Pass 1: index UNET components per prefab (for overrides elsewhere) and decide removals.
    comp_type = {}       # (prefab guid, fileID) -> 'identity'|'transform'|'hud'|'nm'|...
    removed = set()      # (prefab guid, fileID) of components removed from their source prefab
    for f in files:
        if not f.endswith('.prefab'):
            continue
        _, parts = parse(open(f, encoding='utf-8').read())
        g = guid_of(f)
        root_gos = {re.search(r'm_GameObject: \{fileID: (-?\d+)', p['body']).group(1)
                    for p in parts if p['cls'] in ('4', '224') and 'm_Father: {fileID: 0}' in p['body']}
        for p in parts:
            fid, sg = script(p['body'])
            if sg == CUSTOM_NM:
                comp_type[(g, p['id'])] = 'nm'
            if sg != UNET:
                continue
            kind = {ID: 'identity', NT: 'transform', NTC: 'transform', NA: 'animator', NSP: 'startpos',
                    HUD: 'hud', NM: 'nm'}.get(fid, 'unknown')
            comp_type[(g, p['id'])] = kind
            go = re.search(r'm_GameObject: \{fileID: (-?\d+)', p['body']).group(1)
            if kind == 'hud' or (kind == 'identity' and (go not in root_gos or f in NEVER_SPAWNED)):
                removed.add((g, p['id']))

    changed = 0
    for f in files:
        text = open(f, encoding='utf-8').read()
        if UNET not in text and CUSTOM_NM not in text and not any(k[0] in text for k in comp_type):
            continue
        preamble, parts = parse(text)
        g = guid_of(f) if f.endswith('.prefab') else None
        ids = {p['id'] for p in parts}
        # client authority per GameObject (UNET localPlayerAuthority on the object's identity)
        authority = set()
        for p in parts:
            if script(p['body']) == (ID, UNET) and field(p['body'], 'm_LocalPlayerAuthority') == '1':
                authority.add(re.search(r'm_GameObject: \{fileID: (-?\d+)', p['body']).group(1))
        # UNET objects with client authority sync from the owner; one root identity covers the prefab
        prefab_has_authority = bool(authority)
        drop_ids, add_parts = set(), []

        for p in parts:
            body = p['body']
            fid, sg = script(body)
            go_m = re.search(r'm_GameObject: \{fileID: (-?\d+)', body)
            go = go_m.group(1) if go_m else None
            direction = '1' if prefab_has_authority else '0'
            if sg == UNET:
                if (g, p['id']) in removed or fid == HUD:
                    drop_ids.add(p['id'])
                    continue
                if fid == ID:
                    new = '  m_Script: {fileID: 11500000, guid: %s, type: 3}\n' % MIRROR['identity']
                    server_only = field(body, 'm_ServerOnly') or '0'
                    p['body'] = std_lines(body, new) + '  serverOnly: %s\n' % server_only
                elif fid in (NT, NTC):
                    new = '  m_Script: {fileID: 11500000, guid: %s, type: 3}\n' % MIRROR['transform']
                    extra = '  syncDirection: %s\n' % direction
                    target = field(body, 'm_Target')
                    if fid == NTC and target:
                        extra += '  target: %s\n' % target
                    p['body'] = std_lines(body, new) + extra
                elif fid == NA:
                    new = '  m_Script: {fileID: 11500000, guid: %s, type: 3}\n' % MIRROR['animator']
                    p['body'] = std_lines(body, new) + '  syncDirection: %s\n  animator: %s\n' % (
                        direction, field(body, 'm_Animator') or '{fileID: 0}')
                elif fid == NSP:
                    p['body'] = std_lines(body, '  m_Script: {fileID: 11500000, guid: %s, type: 3}\n' % MIRROR['startpos'])
            if (sg == UNET and fid == NM) or (sg == CUSTOM_NM and 'm_NetworkPort' in body):
                if sg == UNET:  # plain UNET NetworkManager (old test scenes) -> Mirror's NetworkManager
                    body = body.replace(re.search(r'  m_Script: [^\n]*', body).group(0),
                                        '  m_Script: {fileID: 11500000, guid: %s, type: 3}' % MIRROR_NM)
                # rename the fields Mirror kept, drop the UNET-only ones (with their nested lines)
                out, skipping = [], False
                for line in body.splitlines(True):
                    top = line.startswith('  ') and not line.startswith('   ') and not line.startswith('  - ')
                    if top:
                        key = line.strip().split(':')[0]
                        skipping = False
                        if key in STD:
                            out.append(line)
                        elif key in NM_FIELDS:
                            out.append(line.replace(key + ':', NM_FIELDS[key] + ':', 1))
                        else:
                            skipping = True
                    elif not skipping:
                        out.append(line)
                kcp_id = str(random.Random(p['id']).randint(10 ** 17, 9 * 10 ** 18))
                while kcp_id in ids:
                    kcp_id = str(int(kcp_id) + 1)
                out.append('  transport: {fileID: %s}\n' % kcp_id)
                p['body'] = ''.join(out)
                add_parts.append({'go': go, 'part': {
                    'cls': '114', 'id': kcp_id, 'header': '--- !u!114 &%s\n' % kcp_id,
                    'body': ('MonoBehaviour:\n  m_ObjectHideFlags: 0\n  m_CorrespondingSourceObject: {fileID: 0}\n'
                             '  m_PrefabInstance: {fileID: 0}\n  m_PrefabAsset: {fileID: 0}\n'
                             '  m_GameObject: {fileID: %s}\n  m_Enabled: 1\n  m_EditorHideFlags: 0\n'
                             '  m_Script: {fileID: 11500000, guid: %s, type: 3}\n  m_Name: \n'
                             '  m_EditorClassIdentifier: \n  port: 7777\n') % (go, MIRROR['kcp'])}})

        # prefab-instance overrides that target migrated components in other prefabs
        def fix_mods(body):
            def repl(m):
                block = m.group(0)
                tm = re.search(r'target: \{fileID: (-?\d+), guid: (\w+)', block)
                pm = re.search(r'propertyPath: (\S+)', block)
                if not tm or not pm:
                    return block
                key = (tm.group(2), tm.group(1))
                kind = comp_type.get(key)
                if kind is None:
                    return block
                path = pm.group(1)
                root = path.split('.')[0]
                if key in removed or kind in ('hud', 'transform', 'animator', 'startpos', 'unknown'):
                    return ''
                if kind == 'identity':
                    return block.replace('propertyPath: m_ServerOnly', 'propertyPath: serverOnly') if root == 'm_ServerOnly' else ''
                if kind == 'nm':
                    if root in NM_FIELDS:
                        return block.replace('propertyPath: ' + root, 'propertyPath: ' + NM_FIELDS[root], 1)
                    return block if not root.startswith('m_') or root in STD else ''
                return block
            return re.sub(r'    - target: \{[^\n]*\n      propertyPath: [^\n]*\n      value: [^\n]*\n(?:        [^\n]*\n)*      objectReference: [^\n]*\n',
                          repl, body)

        new_parts = []
        for p in parts:
            if p['id'] in drop_ids:
                continue
            body = p['body']
            for d in drop_ids:
                body = body.replace('  - component: {fileID: %s}\n' % d, '')
            for add in add_parts:
                if p['id'] == add['go'] and p['cls'] == '1':
                    body = re.sub(r'(  m_Component:\n(?:  - component: \{fileID: -?\d+\}\n)+)',
                                  lambda m: m.group(1) + '  - component: {fileID: %s}\n' % add['part']['id'], body, 1)
            if p['cls'] == '1001':
                body = fix_mods(body)
            p['body'] = body
            new_parts.append(p)
        new_parts += [a['part'] for a in add_parts]
        new_text = preamble + ''.join(p['header'] + p['body'] for p in new_parts)
        if new_text != text:
            open(f, 'w', encoding='utf-8', newline='').write(new_text)
            changed += 1
            print('migrated', f)
    print('%d files changed' % changed)


if __name__ == '__main__':
    main()
